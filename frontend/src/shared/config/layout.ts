/**
 * Ширина, с которой оболочка раскладывается в три колонки: страница фиксируется
 * по высоте вьюпорта, а скроллятся сами колонки.
 *
 * От этого зависит не только вёрстка: Lenis не должен перехватывать колесо там,
 * где документ не скроллится, а ScrollTrigger обязан целиться в колонку, иначе
 * ревилы застревают в стартовом состоянии. Держим одно значение на всех.
 *
 * Дублируется в SCSS как `@include breakpoint(1200px)` — миксины не читают TS,
 * поэтому при изменении правь и `shared/styles/hockey-ui/_layout.scss`.
 */
export const COLUMN_LAYOUT_MIN_WIDTH = 1200

/** Тот же брейкпоинт в виде media query для `window.matchMedia`. */
export const COLUMN_LAYOUT_QUERY = `(min-width: ${COLUMN_LAYOUT_MIN_WIDTH}px)`
